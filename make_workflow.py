#!/usr/bin/env python3
"""Turn an upstream RustDesk checkout's GitHub workflows into the CHANTCH Remote build (Windows + macOS only).

    python3 make_workflow.py --src <branded checkout> --release-tag <e.g. 1.5.0-chantch.1> [--brand brand.env]

Upstream's own build recipe (.github/workflows/flutter-build.yml) is reused, not copied by hand: this keeps only the
jobs that make the Windows exe/msi and the macOS dmg (plus the jobs they need), removes the steps that only serve
RustDesk's paid custom-client generator, points the macOS packaging and the MSI at the branded app name, deletes
every other upstream workflow (CI, nightly, Android, Linux, ...), and writes chantch-build.yml, which runs on a push
of this branch. Every change is anchored and checked like apply.py: if upstream moves a spot, the run stops here.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from apply import die, read_brand  # noqa: E402

KEEP_JOBS = ["generate-bridge", "build-RustDeskTempTopMostWindow", "build-for-windows-flutter", "build-for-macOS"]
DROP_STEPS = {
    # Templates for RustDesk Server Pro's custom-client generator; they also expect rustdesk.exe, which we rename.
    "build-for-windows-flutter": ["Build pre-built MSI template", "Upload unsigned msi template"],
}
JOB_RE = re.compile(r"^  ([A-Za-z0-9_-]+):\s*$")
STEP_RE = re.compile(r"^      - ")


def split_jobs(text: str):
    """(header incl. 'jobs:' line, {job: text}, order). Jobs start at a 2-space key under 'jobs:'."""
    lines = text.splitlines(keepends=True)
    try:
        start = next(i for i, l in enumerate(lines) if l.rstrip() == "jobs:")
    except StopIteration:
        die("flutter-build.yml has no top-level 'jobs:'")
    header, jobs, order, cur = "".join(lines[: start + 1]), {}, [], None
    pending = []  # comment/blank lines before a job key belong to that job
    for l in lines[start + 1:]:
        m = JOB_RE.match(l)
        if m:
            cur = m.group(1)
            order.append(cur)
            jobs[cur] = "".join(pending) + l
            pending = []
        elif cur is None or (l.startswith("  #") or l.strip() == ""):
            pending.append(l)
        else:
            if pending:
                jobs[cur] += "".join(pending)
                pending = []
            jobs[cur] += l
    if pending and cur:
        jobs[cur] += "".join(pending)
    return header, jobs, order


def drop_steps(job: str, job_text: str, names: list) -> str:
    lines = job_text.splitlines(keepends=True)
    starts = [i for i, l in enumerate(lines) if STEP_RE.match(l)]
    if not starts:
        die(f"{job}: no steps found")
    blocks, keep_head = [], "".join(lines[: starts[0]])
    for a, b in zip(starts, starts[1:] + [len(lines)]):
        blocks.append("".join(lines[a:b]))
    out, removed = [], set()
    for blk in blocks:
        m = re.match(r"      - name: (.+)\n", blk)
        if m and m.group(1).strip() in names:
            removed.add(m.group(1).strip())
            continue
        out.append(blk)
    missing = set(names) - removed
    if missing:
        die(f"{job}: steps not found upstream: {sorted(missing)} (update DROP_STEPS in make_workflow.py)")
    return keep_head + "".join(out)


def replace(job: str, text: str, old: str, new: str, count=1) -> str:
    found = text.count(old)
    if (count is None and found == 0) or (count is not None and found != count):
        die(f"{job}: expected {'>=1' if count is None else count} match(es) of {old!r}, found {found} "
            "(update make_workflow.py)")
    return text.replace(old, new)


def needs_of(job_text: str) -> list:
    m = re.search(r"^    needs: \[([^\]]*)\]", job_text, flags=re.M)
    if m:
        return [x.strip() for x in m.group(1).split(",") if x.strip()]
    m = re.search(r"^    needs: ([A-Za-z0-9_-]+)\s*$", job_text, flags=re.M)
    return [m.group(1)] if m else []


def local_uses(text: str) -> set:
    return set(re.findall(r"uses: \./\.github/workflows/([A-Za-z0-9_.-]+\.ya?ml)", text))


def build_workflow(app: str, release_tag: str) -> str:
    return f"""# Generated by make_workflow.py (CHANTCH Remote overlay). Runs when the prepare job pushes this build branch.
name: CHANTCH Remote build {release_tag}

on:
  push:
    branches: ["build/**"]

permissions:
  contents: write

jobs:
  build:
    uses: ./.github/workflows/flutter-build.yml
    secrets: inherit
    with:
      upload-artifact: true
      upload-tag: "{release_tag}"

  rename-assets:
    needs: build
    runs-on: ubuntu-24.04
    steps:
      - name: Rename rustdesk-* assets to {app}-* and add SHA256SUMS
        env:
          GH_TOKEN: ${{{{ github.token }}}}
          GH_REPO: ${{{{ github.repository }}}}
          TAG: "{release_tag}"
        run: |
          set -euo pipefail
          mkdir dl
          gh release view "$TAG" --json assets --jq '.assets[].name' > names.txt
          grep -E '^rustdesk-.*\\.(exe|msi|dmg)$' names.txt > old.txt || {{ echo "no rustdesk-* assets on $TAG"; exit 1; }}
          while read -r n; do
            new="{app}-${{n#rustdesk-}}"
            gh release download "$TAG" -p "$n" -D dl
            mv "dl/$n" "dl/$new"
          done < old.txt
          (cd dl && sha256sum * > SHA256SUMS.txt && cat SHA256SUMS.txt)
          gh release upload "$TAG" dl/* --clobber
          while read -r n; do gh release delete-asset "$TAG" "$n" -y; done < old.txt
          grep -q '\\.exe$' old.txt && grep -q '\\.dmg$' old.txt || {{ echo "missing Windows or macOS build"; exit 1; }}
"""


def main() -> None:
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", required=True, type=Path)
    ap.add_argument("--brand", type=Path, default=here / "brand.env")
    ap.add_argument("--release-tag", required=True)
    a = ap.parse_args()
    if not re.fullmatch(r"\d+\.\d+\.\d+-chantch\.\d+", a.release_tag):
        die(f"--release-tag must look like 1.5.0-chantch.1, got {a.release_tag!r}")
    app = read_brand(a.brand)["APP_NAME"]
    wf = a.src.resolve() / ".github" / "workflows"
    fb = wf / "flutter-build.yml"
    if not fb.exists():
        die(f"{fb} not found")

    header, jobs, order = split_jobs(fb.read_text(encoding="utf-8"))
    for j in KEEP_JOBS:
        if j not in jobs:
            die(f"job {j} not found in upstream flutter-build.yml (update KEEP_JOBS)")
    for j in KEEP_JOBS:
        extra = set(needs_of(jobs[j])) - set(KEEP_JOBS)
        if extra:
            die(f"job {j} now needs {sorted(extra)}, which this build drops (update KEEP_JOBS)")

    for j, names in DROP_STEPS.items():
        jobs[j] = drop_steps(j, jobs[j], names)
    w = "build-for-windows-flutter"
    jobs[w] = replace(w, jobs[w], "          python preprocess.py --arp -d ../../rustdesk\n",
                      f"          Move-Item ../../rustdesk/rustdesk.exe ../../rustdesk/{app}.exe\n"
                      f"          python preprocess.py --arp -d ../../rustdesk --app-name {app}\n")
    m = "build-for-macOS"
    jobs[m] = replace(m, jobs[m], "RustDesk.app", f"{app}.app", count=None)

    kept = header + "".join(jobs[j] for j in order if j in KEEP_JOBS)
    fb.write_text(kept, encoding="utf-8")

    # Keep flutter-build.yml and the local reusable workflows it (transitively) calls; delete everything else.
    keep_files, todo = {"flutter-build.yml"}, set(local_uses(kept))
    while todo:
        f = todo.pop()
        if f in keep_files:
            continue
        if not (wf / f).exists():
            die(f"{f} is used by the kept jobs but missing")
        keep_files.add(f)
        todo |= local_uses((wf / f).read_text(encoding="utf-8"))
    removed = []
    for p in sorted(wf.iterdir()):
        if p.is_file() and p.name not in keep_files:
            p.unlink()
            removed.append(p.name)
    (wf / "chantch-build.yml").write_text(build_workflow(app, a.release_tag), encoding="utf-8")
    print(f"[make_workflow] kept jobs {', '.join(KEEP_JOBS)}; dropped {len(order) - len(KEEP_JOBS)} jobs")
    print(f"[make_workflow] kept workflows {sorted(keep_files)}; removed {len(removed)}: {', '.join(removed)}")
    print(f"[make_workflow] wrote chantch-build.yml for {a.release_tag}")


if __name__ == "__main__":
    main()
